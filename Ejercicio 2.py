#Ejercicio 2. Área y perímetro
#Solicita la base y la altura de un rectángulo.

#Calcula y muestra:

#Área.
#Perímetro.
#Ejemplo:

#Base: 10
#Altura: 5

#Área: 50
#Perímetro: 30

base = float(input("Base: "))
altura = float(input("Altura: "))

area = base * altura
perimetro = 2 * base + 2 * altura

print("Área:", area)
print("Perimetro:", perimetro)
